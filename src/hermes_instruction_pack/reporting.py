"""Status report generation."""

from __future__ import annotations

import json
from pathlib import Path

from . import __version__
from .manifest import Manifest, utcnow
from .modules import module_index
from .validator import validate


def generate_report(root: Path) -> int:
    root = Path(root)
    m = Manifest.load(root / "sources" / "manifest.yaml")
    idx = module_index(root)
    val = validate(root)
    audit_path = root / "reports" / "source-audit.json"
    audit = json.loads(audit_path.read_text(encoding="utf-8")) if audit_path.exists() else {}
    lines = [
        "# Status Summary (generated by `hip report`)",
        "",
        f"- generated_at: {utcnow()}",
        f"- pack_version: {__version__}",
        f"- sources: {m.counts()}",
        f"- source_files_audited: {audit.get('files_scanned', 'n/a')}",
        f"- hash_mismatches: {audit.get('hash_mismatches', 'n/a')}",
        f"- modules: {idx['count']}",
        f"- validation: {'OK' if val['ok'] else 'FAILED ' + str(val['errors'])}",
        "",
        "## Modules",
    ]
    for mod in idx["modules"]:
        if mod.get("valid"):
            lines.append(f"- {mod['module_id']} ({mod.get('kind')}, prio {mod.get('priority')}) — {mod.get('path')}")
    lines += [
        "",
        "## Status legend",
        "- sources audited via hip sources import/audit",
        "- behavioral evaluation: NOT RUN (requires authorized model endpoint; see config/evaluation.yaml)",
    ]
    out = root / "reports" / "status-summary.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0
